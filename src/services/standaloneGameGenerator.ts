import {
  CameraPerspective,
  CanvasScene,
  InferredGameSpec,
  PhysicsProfile,
} from '../types';

/**
 * Generates a complete, self-contained single-file HTML5 + Three.js 3D game
 * from the Figma 2D CanvasScene and the InferredGameSpec.
 * Also includes synthetic bot hooks and postMessage telemetry for the Eval Suite!
 */
export function buildStandaloneThreeJsGameHtml(
  scene: CanvasScene,
  spec: InferredGameSpec,
  modelLabel: string = 'gemini-4-argon'
): string {
  const serializedScene = JSON.stringify(scene);
  const serializedSpec = JSON.stringify(spec);

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>${scene.title} — Generated by ${modelLabel}</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; user-select: none; }
    body { overflow: hidden; background: ${scene.backgroundColor}; font-family: system-ui, -apple-system, sans-serif; color: #f8fafc; }
    #hud {
      position: fixed; top: 12px; left: 12px; right: 12px;
      display: flex; justify-content: space-between; align-items: flex-start;
      pointer-events: none; z-index: 10;
    }
    .hud-card {
      background: rgba(15, 23, 42, 0.82);
      backdrop-filter: blur(8px);
      border: 1px solid rgba(148, 163, 184, 0.25);
      border-radius: 10px;
      padding: 10px 14px;
      font-size: 12px;
      box-shadow: 0 8px 24px rgba(0,0,0,0.4);
    }
    .hud-title { font-weight: 700; font-size: 14px; color: #38bdf8; margin-bottom: 4px; }
    .hud-stat { display: inline-block; margin-right: 12px; font-weight: 600; }
    #banner {
      position: fixed; inset: 0; display: none; align-items: center; justify-content: center;
      background: rgba(9, 13, 22, 0.82); backdrop-filter: blur(6px); z-index: 20;
      flex-direction: column; text-align: center;
    }
    #banner h1 { font-size: 32px; margin-bottom: 8px; color: #c084fc; }
    #banner p { font-size: 15px; color: #cbd5e1; margin-bottom: 16px; }
    #banner button {
      pointer-events: auto; cursor: pointer;
      background: linear-gradient(135deg, #6366f1, #a855f7);
      border: none; color: white; padding: 10px 20px; border-radius: 8px; font-weight: 700;
    }
  </style>
  <script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>
</head>
<body>
  <div id="hud">
    <div class="hud-card">
      <div class="hud-title">${scene.title} (${spec.playerArchetype})</div>
      <div>
        <span class="hud-stat" id="score-el">Shards: 0 / 0</span>
        <span class="hud-stat" id="hp-el">Shield: 100%</span>
        <span class="hud-stat" id="fps-el">FPS: 60</span>
      </div>
      <div style="margin-top:4px;color:#94a3b8;font-size:11px;">
        Model: ${modelLabel} • Cam: ${spec.selectedCameraMode}
      </div>
    </div>
    <div class="hud-card" style="text-align:right;">
      <div style="color:#eab308;font-weight:700;">Objective: ${spec.winCondition}</div>
      <div style="color:#94a3b8;font-size:11px;margin-top:2px;">WASD: Move • SPACE: Jump • SHIFT: Dash/Pulse</div>
    </div>
  </div>
  <div id="banner">
    <h1 id="banner-title">VICTORY!</h1>
    <p id="banner-sub">Quantum Portal Activated</p>
    <button onclick="location.reload()">Play Again</button>
  </div>
  <script>
    (function() {
      const SCENE_DATA = ${serializedScene};
      const SPEC = ${serializedSpec};
      const physics = SPEC.tunedPhysics;

      const renderer = new THREE.WebGLRenderer({ antialias: true });
      renderer.setSize(window.innerWidth, window.innerHeight);
      renderer.shadowMap.enabled = true;
      document.body.appendChild(renderer.domElement);

      const scene = new THREE.Scene();
      scene.background = new THREE.Color(SCENE_DATA.backgroundColor || '#090d16');
      scene.fog = new THREE.FogExp2(SCENE_DATA.fogColor || '#0f172a', 0.008);

      const camera = new THREE.PerspectiveCamera(60, window.innerWidth / window.innerHeight, 0.1, 1000);

      const ambLight = new THREE.AmbientLight(SCENE_DATA.ambientLight || '#38bdf8', 0.65);
      scene.add(ambLight);

      const dirLight = new THREE.DirectionalLight(0xffffff, 1.1);
      dirLight.position.set(40, 80, 50);
      dirLight.castShadow = true;
      scene.add(dirLight);

      const grid = new THREE.GridHelper(140, 35, 0x38bdf8, 0x1e293b);
      grid.position.y = -0.1;
      scene.add(grid);

      const scale = 0.12;
      const offsetX = -SCENE_DATA.width * scale * 0.5;
      const offsetZ = -SCENE_DATA.height * scale * 0.5;

      const platforms = [];
      const collectibles = [];
      const hazards = [];
      const enemies = [];
      const jumpPads = [];
      let goalMesh = null;
      let spawnPos = new THREE.Vector3(0, 3, 0);

      SCENE_DATA.nodes.forEach(node => {
        if (!node.visible) return;
        const w = Math.max(1.2, node.width * scale);
        const d = Math.max(1.2, node.height * scale);
        const h = Math.max(0.5, (node.extrudeHeight || 16) * 0.12);
        const elev = (node.elevation || 0) * 0.12;
        const cx = (node.x + node.width * 0.5) * scale + offsetX;
        const cz = (node.y + node.height * 0.5) * scale + offsetZ;

        if (node.role === 'player_spawn') {
          spawnPos.set(cx, elev + 2.5, cz);
          const pad = new THREE.Mesh(
            new THREE.CylinderGeometry(w * 0.5, w * 0.6, 0.4, 24),
            new THREE.MeshStandardMaterial({ color: 0x38bdf8, emissive: 0x0284c7, emissiveIntensity: 0.6 })
          );
          pad.position.set(cx, elev + 0.2, cz);
          scene.add(pad);
        } else if (node.role === 'platform' || node.role === 'wall' || node.role === 'movable_crate' || node.role === 'decoration') {
          const geo = new THREE.BoxGeometry(w, h, d);
          const mat = new THREE.MeshStandardMaterial({
            color: node.fill || '#334155',
            roughness: 0.4,
            metalness: 0.3
          });
          const mesh = new THREE.Mesh(geo, mat);
          mesh.position.set(cx, elev + h * 0.5, cz);
          mesh.castShadow = true;
          mesh.receiveShadow = true;
          scene.add(mesh);
          platforms.push({ mesh, minX: cx - w/2, maxX: cx + w/2, minZ: cz - d/2, maxZ: cz + d/2, topY: elev + h, role: node.role });
        } else if (node.role === 'collectible') {
          const geo = new THREE.SphereGeometry(0.75, 18, 18);
          geo.scale(1.0, 1.25, 1.0);
          const mat = new THREE.MeshStandardMaterial({ color: 0xfbbf24, emissive: 0xd97706, emissiveIntensity: 0.75, metalness: 0.65, roughness: 0.2 });
          const mesh = new THREE.Mesh(geo, mat);
          const cap = new THREE.Mesh(
            new THREE.CylinderGeometry(0.55, 0.88, 0.5, 16),
            new THREE.MeshStandardMaterial({ color: 0x78350f, roughness: 0.7 })
          );
          cap.position.y = 0.6;
          mesh.add(cap);
          mesh.position.set(cx, elev + 1.6, cz);
          scene.add(mesh);
          collectibles.push({ mesh, collected: false, baseY: elev + 1.6 });
        } else if (node.role === 'hazard') {
          const geo = new THREE.BoxGeometry(w, 0.5, d);
          const mat = new THREE.MeshStandardMaterial({ color: 0xef4444, emissive: 0xdc2626, emissiveIntensity: 0.9 });
          const mesh = new THREE.Mesh(geo, mat);
          mesh.position.set(cx, elev + 0.25, cz);
          scene.add(mesh);
          hazards.push({ mesh, minX: cx - w/2, maxX: cx + w/2, minZ: cz - d/2, maxZ: cz + d/2, topY: elev + 0.8 });
        } else if (node.role === 'jump_pad') {
          const geo = new THREE.CylinderGeometry(w * 0.5, w * 0.6, 0.6, 20);
          const mat = new THREE.MeshStandardMaterial({ color: 0x10b981, emissive: 0x059669, emissiveIntensity: 0.9 });
          const mesh = new THREE.Mesh(geo, mat);
          mesh.position.set(cx, elev + 0.3, cz);
          scene.add(mesh);
          jumpPads.push({ mesh, x: cx, z: cz, y: elev + 0.6, radius: Math.max(1.8, w * 0.55), boost: (node.bounciness || 1.8) });
        } else if (node.role === 'enemy_patrol') {
          const geo = new THREE.ConeGeometry(1.1, 2.2, 6);
          const mat = new THREE.MeshStandardMaterial({ color: 0xf97316, emissive: 0xea580c, emissiveIntensity: 0.6 });
          const mesh = new THREE.Mesh(geo, mat);
          mesh.position.set(cx, elev + 1.4, cz);
          scene.add(mesh);
          enemies.push({ mesh, originX: cx, originZ: cz, y: elev + 1.4, speed: node.speed || 1.4, phase: Math.random() * 6.28 });
        } else if (node.role === 'goal_portal') {
          const geo = new THREE.TorusGeometry(2.0, 0.35, 16, 36);
          const mat = new THREE.MeshStandardMaterial({ color: 0xa855f7, emissive: 0x9333ea, emissiveIntensity: 1.0 });
          goalMesh = new THREE.Mesh(geo, mat);
          goalMesh.position.set(cx, elev + 2.4, cz);
          scene.add(goalMesh);
        }
      });

      const player = new THREE.Group();
      const furMat = new THREE.MeshStandardMaterial({ color: 0xea580c, emissive: 0x9a3412, emissiveIntensity: 0.35, roughness: 0.45 });
      const body = new THREE.Mesh(new THREE.SphereGeometry(0.85, 20, 20), furMat);
      const head = new THREE.Mesh(new THREE.SphereGeometry(0.6, 18, 18), furMat);
      head.position.set(0, 0.78, 0.25);
      const tail = new THREE.Mesh(new THREE.SphereGeometry(0.75, 18, 18), furMat);
      tail.position.set(0, 0.7, -1.0);
      player.add(body, head, tail);
      player.position.copy(spawnPos);
      player.castShadow = true;
      scene.add(player);

      const keys = {};
      let velY = 0;
      let jumpsLeft = physics.doubleJump ? 2 : 1;
      let score = 0;
      let hp = 100;
      let gameWon = false;

      window.addEventListener('keydown', e => {
        keys[e.code] = true;
        if (e.code === 'Space' && jumpsLeft > 0) {
          velY = physics.jumpForce || 12;
          jumpsLeft--;
        }
      });
      window.addEventListener('keyup', e => { keys[e.code] = false; });

      // Synthetic Bot Support for Eval Suite
      window.addEventListener('message', e => {
        if (e.data && e.data.type === 'BOT_STEP') {
          keys['KeyW'] = e.data.forward;
          keys['KeyD'] = e.data.right;
          keys['KeyA'] = e.data.left;
          if (e.data.jump && jumpsLeft > 0) {
            velY = physics.jumpForce || 12;
            jumpsLeft--;
          }
        }
      });

      let lastTime = performance.now();
      let frameCount = 0;
      let fps = 60;

      function animate(now) {
        requestAnimationFrame(animate);
        const dt = Math.min(0.05, (now - lastTime) / 1000);
        lastTime = now;
        frameCount++;

        if (!gameWon) {
          const speed = (physics.moveSpeed || 12) * (keys['ShiftLeft'] ? (physics.dashMultiplier || 1.8) : 1);
          let dx = 0, dz = 0;
          if (keys['KeyW'] || keys['ArrowUp']) dz -= 1;
          if (keys['KeyS'] || keys['ArrowDown']) dz += 1;
          if (keys['KeyA'] || keys['ArrowLeft']) dx -= 1;
          if (keys['KeyD'] || keys['ArrowRight']) dx += 1;
          if (dx !== 0 || dz !== 0) {
            const len = Math.hypot(dx, dz);
            player.position.x += (dx / len) * speed * dt;
            player.position.z += (dz / len) * speed * dt;
          }

          velY -= (physics.gravity || 22) * dt;
          player.position.y += velY * dt;

          // Floor & Platform Collisions
          let grounded = false;
          for (const p of platforms) {
            if (player.position.x >= p.minX - 0.8 && player.position.x <= p.maxX + 0.8 &&
                player.position.z >= p.minZ - 0.8 && player.position.z <= p.maxZ + 0.8) {
              if (player.position.y - 1.0 <= p.topY && player.position.y - 1.0 >= p.topY - 2.2 && velY <= 0) {
                player.position.y = p.topY + 1.0;
                velY = 0;
                grounded = true;
              }
            }
          }
          if (player.position.y < 1.0) {
            player.position.y = 1.0;
            velY = 0;
            grounded = true;
          }
          if (grounded) jumpsLeft = physics.doubleJump ? 2 : 1;

          // Jump pads
          for (const jp of jumpPads) {
            jp.mesh.rotation.y += dt * 2;
            if (Math.hypot(player.position.x - jp.x, player.position.z - jp.z) < jp.radius &&
                Math.abs(player.position.y - jp.y) < 2.5) {
              velY = (physics.jumpForce || 12) * jp.boost;
            }
          }

          // Collectibles
          const magnet = physics.magnetRadius || 3.0;
          for (const c of collectibles) {
            if (c.collected) continue;
            c.mesh.rotation.y += dt * 3;
            c.mesh.position.y = c.baseY + Math.sin(now * 0.004) * 0.35;
            const dist = player.position.distanceTo(c.mesh.position);
            if (dist < magnet) {
              c.mesh.position.lerp(player.position, dt * 6);
            }
            if (dist < 1.8) {
              c.collected = true;
              c.mesh.visible = false;
              score++;
            }
          }

          // Enemies
          for (const en of enemies) {
            en.phase += dt * en.speed;
            en.mesh.position.x = en.originX + Math.sin(en.phase) * 5.5;
            en.mesh.rotation.y += dt * 4;
            if (player.position.distanceTo(en.mesh.position) < 2.0) {
              hp = Math.max(0, hp - 25 * dt);
            }
          }

          // Goal Portal
          if (goalMesh) {
            goalMesh.rotation.z += dt * 2.5;
            if (player.position.distanceTo(goalMesh.position) < 2.8) {
              gameWon = true;
              document.getElementById('banner').style.display = 'flex';
            }
          }
        }

        // Camera follow
        if (SPEC.selectedCameraMode === 'isometric_tactical') {
          camera.position.lerp(new THREE.Vector3(player.position.x + 22, player.position.y + 26, player.position.z + 22), 0.08);
        } else if (SPEC.selectedCameraMode === 'top_down_action') {
          camera.position.lerp(new THREE.Vector3(player.position.x, player.position.y + 32, player.position.z + 10), 0.1);
        } else {
          camera.position.lerp(new THREE.Vector3(player.position.x, player.position.y + 11, player.position.z + 18), 0.1);
        }
        camera.lookAt(player.position);

        document.getElementById('score-el').textContent = 'Shards: ' + score + ' / ' + collectibles.length;
        document.getElementById('hp-el').textContent = 'Shield: ' + Math.round(hp) + '%';

        renderer.render(scene, camera);

        if (frameCount % 20 === 0 && window.parent !== window) {
          window.parent.postMessage({
            type: 'GAME_RUNTIME_HEARTBEAT',
            fps,
            score,
            totalCollectibles: collectibles.length,
            goalReached: gameWon,
            entityCount: SCENE_DATA.nodes.length
          }, '*');
        }
      }
      requestAnimationFrame(animate);
    })();
  </script>
</body>
</html>`;
}
